/** 前端演示合成：称号池 */
const SYNTH_TITLES: readonly string[] = ['豪杰', '精英', '新锐', '翘楚', '新星']

/**
 * 逐字段来源标注（PRD v1.3 §0.1.2）。
 * excel = schema 真值（UID/昵称/加入时间/战报挑战次数）；
 * synthetic = 前端演示合成（职位/积分/状态/地区/称号/团队等），按 hash(uid) 确定性生成。
 */
function memberSource(): FieldSourceMap<Member> {
  return {
    id: 'synthetic',
    account: 'excel',
    name: 'excel',
    role: 'synthetic',
    job: 'synthetic',
    level: 'synthetic',
    title: 'synthetic',
    points: 'synthetic',
    frozen: 'synthetic',
    status: 'synthetic',
    join: 'excel',
    lastActive: 'synthetic',
    team: 'synthetic',
    captain: 'synthetic',
    province: 'synthetic',
    city: 'synthetic',
    district: 'synthetic',
    accountStatus: 'synthetic',
    lastLogin: 'synthetic',
    challengeCount: 'excel',
  }
}

/**
 * 单行 → Member。缺失字段全部由 hash(uid) 确定性合成，刷新后完全一致。
 * @param row Excel 原始行
 * @param index 1 起顺序号，用于生成 M### ID
 * @param challengeCount 来自深渊战报的真实挑战次数（无记录时为 0）
 */
export function buildMemberFrom(row: RawMemberRow, index: number, challengeCount = 0): Member {
  const [uid, name, joinRaw] = row
  const join = dateOf(joinRaw)
  const role = synthesizedRole(uid)
  const status = role === 'admin' || role === 'leader' || hashInt(uid, 0, 24, 7) !== 0 ? 'active' : 'left'
  const region = hashInt(uid, 0, 9, 11) < 5 ? hashPick(uid, SYNTH_REGIONS) : null

  return {
    id: padId('M', index),
    account: uid,
    name,
    role,
    // 职业 / 等级原 Excel 不存在：统一 null，界面显示「—」
    job: null,
    level: null,
    title: hashPick(uid, SYNTH_TITLES),
    points: 200 + hashInt(uid, 0, 3200, 3),
    frozen: hashInt(uid, 0, 180, 4),
    status,
    join,
    lastActive: timeOf(joinRaw, 5),
    team: status === 'active' ? 'T' + String(hashInt(uid, 1, 6, 6)) : null,
    captain: status === 'active' && hashInt(uid, 0, 10, 8) === 0,
    province: region ? region[0] : '',
    city: region ? region[1] : '',
    district: region ? region[2] : '',
    accountStatus: status === 'active' ? 'active' : 'disabled',
    lastLogin: timeOf(joinRaw, 9),
    challengeCount,
    source: memberSource(),
  }
}

/** 99 行 Excel → 99 名成员（未登记 UID 由 members.ts 基于集合差补建） */
export function buildMembers(): Member[] {
  return RAW_MEMBER_ROWS.map((row, index) => buildMemberFrom(row, index + 1))
}
