/** 达标积分（前端演示规则；真实规则配置见 points.ts 的 RULES） */
function qualifiedPoints(rank: number, damage: number): number {
  if (damage < 50_000_000) return 0
  let points = rank <= 5 ? 120 : rank <= 20 ? 90 : rank <= 40 ? 60 : rank <= 60 ? 40 : 20
  if (damage >= 70_000_000) points += 10
  return points
}

/**
 * 构造结构化战报。
 * @param memberUids 成员表 UID 集合，用于运行时计算未登记 UID
 */
export function buildAbyssReport(memberUids: readonly string[] = []): AbyssReport {
  const known = new Set(memberUids)
  const rows: AbyssReportRow[] = RAW_ABYSS_ROWS.map(([rank, name, uid, damage, challenges]) => {
    const qualified = damage >= 50_000_000 && (rank > 60 ? challenges >= 3 : true)
    return {
      rank,
      name,
      uid,
      damage,
      challenges,
      qualified,
      // memberUids 为空时不做判定，避免误标
      unregistered: memberUids.length > 0 && !known.has(uid),
      points: qualifiedPoints(rank, damage),
      // 第 93-100 名真实未参与记录：0 伤害 + 0 挑战，UI 必须保留并灰显
      absent: damage === 0 && challenges === 0,
    }
  })

  return {
    title: ABYSS_TITLE,
    file: '2026-11-13_深渊战报.xlsx',
    week: ABYSS_WEEK,
    date: ABYSS_DATE,
    uploadedAt: '2026-11-14 09:30',
    uploadedBy: '烟火',
    rows,
  }
}

